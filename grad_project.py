        imagenet_mean = np.array([
            0.485,
            0.456,
            0.406
        ])

        imagenet_std = np.array([
            0.229,
            0.224,
            0.225
        ])

        image_to_save = (
            normalized_image * imagenet_std
            + imagenet_mean
        )

        image_to_save = np.clip(
            image_to_save * 255.0,
            0,
            255
        ).astype(np.uint8)


        # RGB → BGR
        image_to_save = cv2.cvtColor(
            image_to_save,
            cv2.COLOR_RGB2BGR
        )


        # ----------------------------------------------------
        # Save Image
        # ----------------------------------------------------

        output_image_path = (
            output_images / image_path.name
        )

        cv2.imwrite(
            str(output_image_path),
            image_to_save
        )


        # ----------------------------------------------------
        # Transform and Save YOLO Labels
        # ----------------------------------------------------

        label_path = (
            input_labels /
            f"{image_path.stem}.txt"
        )

        output_label_path = (
            output_labels /
            f"{image_path.stem}.txt"
        )

        transform_yolo_labels(
            label_path,
            output_label_path,
            original_width,
            original_height,
            scale,
            pad_x,
            pad_y,
            target_size=416
        )


