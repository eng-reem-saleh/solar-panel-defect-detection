def apply_clahe(image):

    lab = cv2.cvtColor(image, cv2.COLOR_RGB2LAB)

    l, a, b = cv2.split(lab)

    clahe = cv2.createCLAHE(
        clipLimit=2.0,
        tileGridSize=(8, 8)
    )

    l_clahe = clahe.apply(l)

    lab_clahe = cv2.merge([
        l_clahe,
        a,
        b
    ])

    image_clahe = cv2.cvtColor(
        lab_clahe,
        cv2.COLOR_LAB2RGB
    )

    return image_clahe


